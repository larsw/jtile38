package io.jtile38.geojson.geometry

import kotlin.test.Test
import kotlin.test.assertEquals

class SegmentTest {
    @Test
    fun segmentContainsPoint() {
        expect(S(0, 0, 1, 1).containsPoint(P(0, 0)))
        expect(S(0, 0, 1, 1).containsPoint(P(0.5, 0.5)))
        expect(S(0, 0, 1, 1).containsPoint(P(1, 1)))
        expect(!S(0, 0, 1, 1).containsPoint(P(1.1, 1.1)))
        expect(!S(0, 0, 1, 1).containsPoint(P(0.5, 0.6)))
        expect(!S(0, 0, 1, 1).containsPoint(P(-0.1, -0.1)))
    }

    @Test
    fun segmentCollinearPoint() {
        expect(S(0, 0, 1, 1).collinearPoint(P(-1, -1)))
        expect(S(0, 0, 1, 1).collinearPoint(P(0.5, 0.5)))
        expect(S(0, 0, 1, 1).collinearPoint(P(2, 2)))
        expect(S(1, 1, 0, 0).collinearPoint(P(-1, -1)))
        expect(S(1, 1, 0, 0).collinearPoint(P(0.5, 0.5)))
        expect(S(1, 1, 0, 0).collinearPoint(P(2, 2)))
        expect(S(1, 0, 0, 1).collinearPoint(P(2, -1)))
        expect(S(1, 0, 0, 1).collinearPoint(P(0.5, 0.5)))
        expect(S(1, 0, 0, 1).collinearPoint(P(-1, 2)))
        expect(S(0, 1, 1, 0).collinearPoint(P(2, -1)))
        expect(S(0, 1, 1, 0).collinearPoint(P(0.5, 0.5)))
        expect(S(0, 1, 1, 0).collinearPoint(P(-1, 2)))
    }

    @Test
    fun segmentContainsSegment() {
        expect(S(0, 0, 10, 10).containsSegment(S(0, 0, 10, 10)))
        expect(S(0, 0, 10, 10).containsSegment(S(2, 2, 10, 10)))
        expect(S(0, 0, 10, 10).containsSegment(S(2, 2, 8, 8)))
        expect(!S(0, 0, 10, 10).containsSegment(S(-1, -1, 8, 8)))
    }

